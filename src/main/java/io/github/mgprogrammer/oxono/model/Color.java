package io.github.mgprogrammer.oxono.model;

/**
 * The Color enum represents the primary colors used within the game context.
 * It defines the distinct colors that can be assigned to players or
 * elements of the board.
 *
 * Enum Constants:
 * - PINK: Represents the pink color, typically assigned to one player.
 * - BLACK: Represents the black color, typically assigned to another player.
 * - BLUE: Represents the blue color, which assigned to a totem.
 */
public enum Color {
    PINK, BLACK, BLUE
}
